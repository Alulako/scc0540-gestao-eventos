BEGIN;
CREATE TABLE pessoa (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome varchar(120) NOT NULL CHECK (btrim(nome) <> ''),
    email varchar(254) NOT NULL UNIQUE CHECK (position('@' in email) > 1)
);
CREATE TABLE promotor (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pessoa_id bigint UNIQUE REFERENCES pessoa(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    organizacao varchar(160),
    CHECK ((pessoa_id IS NOT NULL AND organizacao IS NULL) OR
           (pessoa_id IS NULL AND organizacao IS NOT NULL AND btrim(organizacao) <> ''))
);
CREATE TABLE evento (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome varchar(160) NOT NULL CHECK (btrim(nome) <> ''),
    edicao integer NOT NULL CHECK (edicao > 0),
    inicio timestamp NOT NULL,
    fim timestamp NOT NULL CHECK (fim > inicio),
    UNIQUE (nome, edicao)
);
CREATE TABLE promove (
    promotor_id bigint REFERENCES promotor(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    evento_id bigint REFERENCES evento(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    PRIMARY KEY (promotor_id, evento_id)
);
CREATE TABLE espaco (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome varchar(120) NOT NULL UNIQUE CHECK (btrim(nome) <> ''),
    capacidade integer NOT NULL CHECK (capacidade > 0),
    recursos text NOT NULL DEFAULT ''
);
CREATE TABLE atividade (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id bigint NOT NULL REFERENCES evento(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    titulo varchar(160) NOT NULL CHECK (btrim(titulo) <> ''),
    descricao text NOT NULL DEFAULT '',
    tipo varchar(25) NOT NULL CHECK (tipo IN
        ('palestra','workshop','minicurso','painel','mesa-redonda','apresentacao'))
);
CREATE TABLE sessao (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    atividade_id bigint NOT NULL REFERENCES atividade(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    espaco_id bigint NOT NULL REFERENCES espaco(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    inicio timestamp NOT NULL,
    fim timestamp NOT NULL CHECK (fim > inicio),
    requer_inscricao boolean NOT NULL DEFAULT false,
    limite_vagas integer CHECK (limite_vagas > 0),
    CHECK (requer_inscricao OR limite_vagas IS NULL)
);
CREATE TABLE inscricao_evento (
    pessoa_id bigint REFERENCES pessoa(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    evento_id bigint REFERENCES evento(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    status varchar(12) NOT NULL DEFAULT 'confirmada'
        CHECK (status IN ('confirmada','espera','cancelada')),
    inscrito_em timestamptz NOT NULL DEFAULT current_timestamp,
    PRIMARY KEY (pessoa_id, evento_id)
);
CREATE TABLE inscricao_sessao (
    pessoa_id bigint REFERENCES pessoa(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    sessao_id bigint REFERENCES sessao(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    status varchar(12) NOT NULL DEFAULT 'confirmada'
        CHECK (status IN ('confirmada','espera','cancelada')),
    inscrito_em timestamptz NOT NULL DEFAULT current_timestamp,
    PRIMARY KEY (pessoa_id, sessao_id)
);
CREATE TABLE papel_evento (
    pessoa_id bigint REFERENCES pessoa(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    evento_id bigint REFERENCES evento(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    papel varchar(25) CHECK (papel IN ('organizador','colaborador')),
    PRIMARY KEY (pessoa_id, evento_id, papel)
);
CREATE TABLE papel_sessao (
    pessoa_id bigint REFERENCES pessoa(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    sessao_id bigint REFERENCES sessao(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    papel varchar(25) CHECK (papel IN ('palestrante','instrutor','moderador')),
    PRIMARY KEY (pessoa_id, sessao_id, papel)
);
CREATE TABLE historico_sessao (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    sessao_id bigint NOT NULL REFERENCES sessao(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    inicio_anterior timestamp NOT NULL,
    fim_anterior timestamp NOT NULL,
    espaco_anterior bigint NOT NULL REFERENCES espaco(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    inicio_novo timestamp NOT NULL,
    fim_novo timestamp NOT NULL,
    espaco_novo bigint NOT NULL REFERENCES espaco(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    alterado_em timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX atividade_evento_idx ON atividade(evento_id);
CREATE INDEX sessao_atividade_idx ON sessao(atividade_id);
CREATE INDEX sessao_espaco_inicio_idx ON sessao(espaco_id, inicio);
CREATE INDEX inscricao_sessao_status_idx ON inscricao_sessao(sessao_id, status);
CREATE INDEX inscricao_evento_status_idx ON inscricao_evento(evento_id, status);
CREATE INDEX historico_sessao_idx ON historico_sessao(sessao_id, alterado_em);

-- Serializa escritas que afetam invariantes ANTES de obter locks de linhas.
-- Escopo pequeno/didatico: privilegia corretude sobre throughput.
-- As validacoes VOLATILE em READ COMMITTED enxergam commits apos a espera.
CREATE FUNCTION serializar_regras() RETURNS trigger LANGUAGE plpgsql VOLATILE AS $$
BEGIN
    IF current_setting('transaction_isolation') <> 'read committed' THEN
        RAISE EXCEPTION 'Escritas de planejamento exigem isolamento READ COMMITTED'
            USING ERRCODE = '25000';
    END IF;
    PERFORM pg_advisory_xact_lock(540, 2026);
    RETURN NULL;
END;
$$;
CREATE TRIGGER serial_evento BEFORE INSERT OR UPDATE OR DELETE ON evento
FOR EACH STATEMENT EXECUTE FUNCTION serializar_regras();
CREATE TRIGGER serial_atividade BEFORE INSERT OR UPDATE OR DELETE ON atividade
FOR EACH STATEMENT EXECUTE FUNCTION serializar_regras();
CREATE TRIGGER serial_sessao BEFORE INSERT OR UPDATE OR DELETE ON sessao
FOR EACH STATEMENT EXECUTE FUNCTION serializar_regras();
CREATE TRIGGER serial_espaco BEFORE INSERT OR UPDATE OR DELETE ON espaco
FOR EACH STATEMENT EXECUTE FUNCTION serializar_regras();
CREATE TRIGGER serial_inscricao_evento BEFORE INSERT OR UPDATE OR DELETE ON inscricao_evento
FOR EACH STATEMENT EXECUTE FUNCTION serializar_regras();
CREATE TRIGGER serial_inscricao_sessao BEFORE INSERT OR UPDATE OR DELETE ON inscricao_sessao
FOR EACH STATEMENT EXECUTE FUNCTION serializar_regras();

-- Finalidade 1: periodo, inclusive ao alterar os pais de uma sessao.
CREATE FUNCTION validar_periodo() RETURNS trigger LANGUAGE plpgsql VOLATILE AS $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM sessao s JOIN atividade a ON a.id = s.atividade_id
        JOIN evento e ON e.id = a.evento_id
        WHERE s.inicio < e.inicio OR s.fim > e.fim
    ) THEN
        RAISE EXCEPTION 'Sessao fora do periodo do evento' USING ERRCODE = '23514';
    END IF;
    RETURN NULL;
END;
$$;
CREATE TRIGGER periodo_sessao AFTER INSERT OR UPDATE ON sessao
FOR EACH STATEMENT EXECUTE FUNCTION validar_periodo();
CREATE TRIGGER periodo_evento AFTER UPDATE ON evento
FOR EACH STATEMENT EXECUTE FUNCTION validar_periodo();
CREATE TRIGGER periodo_atividade AFTER UPDATE ON atividade
FOR EACH STATEMENT EXECUTE FUNCTION validar_periodo();

-- Finalidade 2: reserva exclusiva do espaco; intervalos [inicio,fim).
CREATE FUNCTION validar_conflito() RETURNS trigger LANGUAGE plpgsql VOLATILE AS $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM sessao a JOIN sessao b
          ON a.id < b.id AND a.espaco_id = b.espaco_id
         AND a.inicio < b.fim AND b.inicio < a.fim
    ) THEN
        RAISE EXCEPTION 'Conflito de horario no mesmo espaco' USING ERRCODE = '23514';
    END IF;
    RETURN NULL;
END;
$$;
CREATE TRIGGER conflito_sessao AFTER INSERT OR UPDATE ON sessao
FOR EACH STATEMENT EXECUTE FUNCTION validar_conflito();

-- Finalidade 3: limite configurado e lotacao, incluindo mudancas de capacidade.
CREATE FUNCTION validar_vagas() RETURNS trigger LANGUAGE plpgsql VOLATILE AS $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM sessao s JOIN espaco ep ON ep.id = s.espaco_id
        WHERE s.limite_vagas > ep.capacidade
    ) THEN
        RAISE EXCEPTION 'Limite de vagas maior que capacidade fisica' USING ERRCODE = '23514';
    END IF;
    IF EXISTS (
        SELECT 1 FROM sessao s JOIN espaco ep ON ep.id = s.espaco_id
        JOIN inscricao_sessao i ON i.sessao_id = s.id AND i.status = 'confirmada'
        GROUP BY s.id, ep.capacidade
        HAVING count(*) > coalesce(s.limite_vagas, ep.capacidade)
    ) THEN
        RAISE EXCEPTION 'Vagas esgotadas: confirmacoes excedem lotacao' USING ERRCODE = '23514';
    END IF;
    RETURN NULL;
END;
$$;
CREATE TRIGGER vagas_inscricao AFTER INSERT OR UPDATE ON inscricao_sessao
FOR EACH STATEMENT EXECUTE FUNCTION validar_vagas();
CREATE TRIGGER vagas_sessao AFTER INSERT OR UPDATE ON sessao
FOR EACH STATEMENT EXECUTE FUNCTION validar_vagas();
CREATE TRIGGER vagas_espaco AFTER UPDATE ON espaco
FOR EACH STATEMENT EXECUTE FUNCTION validar_vagas();

-- Finalidade 4: elegibilidade; cancelamento geral depende de cancelar as sessoes.
CREATE FUNCTION validar_inscricao() RETURNS trigger LANGUAGE plpgsql VOLATILE AS $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM inscricao_sessao i JOIN sessao s ON s.id = i.sessao_id
        JOIN atividade a ON a.id = s.atividade_id
        LEFT JOIN inscricao_evento ie ON ie.pessoa_id = i.pessoa_id AND ie.evento_id = a.evento_id
        WHERE NOT s.requer_inscricao OR
            (i.status = 'confirmada' AND ie.status IS DISTINCT FROM 'confirmada')
    ) THEN
        RAISE EXCEPTION 'Sessao deve exigir inscricao; confirmacao exige inscricao geral confirmada'
            USING ERRCODE = '23514';
    END IF;
    RETURN NULL;
END;
$$;
CREATE TRIGGER elegibilidade_inscricao AFTER INSERT OR UPDATE ON inscricao_sessao
FOR EACH STATEMENT EXECUTE FUNCTION validar_inscricao();
CREATE TRIGGER elegibilidade_evento AFTER UPDATE OR DELETE ON inscricao_evento
FOR EACH STATEMENT EXECUTE FUNCTION validar_inscricao();
CREATE TRIGGER elegibilidade_sessao AFTER UPDATE ON sessao
FOR EACH STATEMENT EXECUTE FUNCTION validar_inscricao();
CREATE TRIGGER elegibilidade_atividade AFTER UPDATE ON atividade
FOR EACH STATEMENT EXECUTE FUNCTION validar_inscricao();

-- Finalidade 5: registrar apenas alteracoes efetivas e aceitas de programacao.
CREATE FUNCTION registrar_historico() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF ROW(OLD.inicio, OLD.fim, OLD.espaco_id) IS DISTINCT FROM
       ROW(NEW.inicio, NEW.fim, NEW.espaco_id) THEN
        INSERT INTO historico_sessao
            (sessao_id, inicio_anterior, fim_anterior, espaco_anterior,
             inicio_novo, fim_novo, espaco_novo)
        VALUES (NEW.id, OLD.inicio, OLD.fim, OLD.espaco_id,
                NEW.inicio, NEW.fim, NEW.espaco_id);
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER historico_sessao_update AFTER UPDATE ON sessao
FOR EACH ROW EXECUTE FUNCTION registrar_historico();
COMMIT;
